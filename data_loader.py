def _make_word_notes(prompt: str, choices: list[str]) -> tuple[WordNote, ...]:
    words = dict.fromkeys(
        match.group(0).casefold()
        for text in (prompt, *choices)
        for match in _WORD.finditer(text)
    )
    missing = sorted(set(words) - WORD_GUIDE.keys())
    if missing:
        raise ValueError(f"Missing beginner word guide(s): {', '.join(missing)}")
    return tuple(
        WordNote(word, *WORD_GUIDE[word])
        for word in words
    )


def _build_question(row: dict[str, Any]) -> Question:
    choices = tuple(row["choices"])
    if len(choices) != 4 or not 0 <= row["answer"] < 4:
        raise ValueError(f"Each question needs four choices and a valid answer: {row['prompt']}")
    correct = row["answer"]
    reason = row["why"]
    wrong = tuple(
        reason if index == correct
        else f"'{choice}'는 {row['focus']}에 맞지 않아요. {reason}"
        for index, choice in enumerate(choices)
    )
    return Question(
        prompt=row["prompt"],
        choices=choices,  # type: ignore[arg-type]
        correct_index=correct,
        focus=row["focus"],
        grammar_ko=row["grammar"],
        why_correct_ko=reason,
        why_wrong_ko=wrong,  # type: ignore[arg-type]
        word_notes=_make_word_notes(row["prompt"], list(choices)),
    )


def load_questions(level: str) -> list[Question]:
    """Load one curated 20-question level and validate it before play."""
    if level not in LEVELS:
        raise ValueError(f"Unknown level '{level}'. Choose elementary, middle, or high.")
    rows = QUESTION_BANKS[level]
    if len(rows) != 20:
        raise ValueError(f"The {level} bank must contain exactly 20 questions; found {len(rows)}.")
    return [_build_question(row) for row in rows]
